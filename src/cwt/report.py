"""Evaluation report (Markdown) built only from numbers produced by the actual run."""
from __future__ import annotations

import pandas as pd

from cwt.model import WFConfig


def _md_table(df: pd.DataFrame, floatfmt: str = "{:.3f}") -> str:
    cols = list(df.columns)
    out = ["| " + " | ".join([df.index.name or ""] + [str(c) for c in cols]) + " |",
           "|" + "---|" * (len(cols) + 1)]
    for idx, row in df.iterrows():
        cells = [floatfmt.format(v) if isinstance(v, float) else str(v) for v in row]
        out.append("| " + " | ".join([str(idx)] + cells) + " |")
    return "\n".join(out)


def build_report(metrics: pd.DataFrame, folds: pd.DataFrame, gain: pd.Series, cfg: WFConfig,
                 n_trades: int, span: tuple, capital: float, ppy: int, sources: dict,
                 ranking: pd.DataFrame | None, synthetic: bool, backtest: bool = False, uncertainty: dict | None = None) -> str:
    L = ["# Evaluation Report: Macro-aware strategy-permutation model", ""]
    if synthetic:
        L += ["> **WARNING: SYNTHETIC DATA.** Trades and/or macro events in this run were generated by "
              "`cwt demo-data`. These numbers only show that the pipeline runs end to end. They say nothing about "
              "real strategies or markets.", ""]
    if backtest:
        L += ["> **NOTE: the trades are SIMULATED.** They come from backtesting strategy permutations on public "
              "price bars (fills at next-bar open, per-side cost and slippage assumptions from `build-trade-log`), "
              "not from live trading records. Results show how the model ranks simulated strategies; they are not "
              "evidence of live profitability.", ""]
    L += ["## Setup",
          f"- Trades: {n_trades:,} from {span[0]:%Y-%m-%d} to {span[1]:%Y-%m-%d}; data sources: {sources}",
          f"- Model: LightGBM ({'regression on trade P&L' if cfg.target == 'pnl' else 'classifier on win/loss'}), "
          f"refit every fold",
          f"- Walk-forward: expanding window, min train {cfg.train_min_days}d, test {cfg.test_days}d, "
          f"step {cfg.step_days}d, embargo {cfg.embargo_days}d, top-k permutations = {cfg.top_k}",
          f"- Returns = daily P&L / ${capital:,.0f} initial capital (non-compounded); annualisation = {ppy} days; "
          "risk-free rate = 0; Sortino target = 0",
          "", "## Out-of-sample strategy metrics",
          "All policies are evaluated on the same out-of-sample days. `all_trades` is the do-nothing-clever baseline.", "",
          _md_table(metrics[["n_trades", "total_pnl", "avg_pnl_per_trade", "hit_rate", "sharpe", "sortino",
                             "max_drawdown_pct", "max_drawdown_abs"]].astype(float)), "",
          "## Per-fold model quality (out-of-sample)"]
    show = folds.drop(columns=["train_end", "test_end"]).copy()
    show["test_start"] = show["test_start"].dt.strftime("%Y-%m-%d")
    L += [_md_table(show.set_index("fold")), "",
          f"Mean out-of-sample rank correlation (IC): **{folds['ic_spearman'].mean():.3f}** "
          f"(folds > 0: {(folds['ic_spearman'] > 0).sum()}/{folds['ic_spearman'].notna().sum()}). "
          "An IC near 0 means the model has no usable ranking skill.", "",
          "## Top features (mean share of gain)", _md_table(gain.head(10).to_frame("gain")), ""]
    if ranking is not None and not ranking.empty:
        L += ["## Permutation ranking for the latest window (not validated out-of-sample)",
              _md_table(ranking.head(10).set_index("strategy_id")), ""]
    if uncertainty:
        L += ["## Uncertainty", "Moving-block bootstrap (5-day blocks, 2000 resamples) 95% intervals for the Sharpe ratio:", "",
              "| policy | Sharpe | 95% interval |", "|---|---|---|"]
        for name, (lo, hi) in uncertainty["sharpe_ci"].items():
            L.append(f"| {name} | {metrics.loc[name, 'sharpe']:.2f} | [{lo:.2f}, {hi:.2f}] |")
        t = uncertainty["taken_vs_skipped"]
        verdict = ("the interval excludes 0, which is evidence the model separates better from worse trades"
                   if t["lo"] > 0 else "the interval includes 0, so there is no statistical evidence of skill"
                   if t["hi"] >= 0 else "the interval is below 0, i.e. the model picks WORSE trades than it skips")
        L += ["", f"**Taken vs skipped trades (model_trade_filter):** mean P&L taken {t['mean_taken']:.2f}, skipped "
              f"{t['mean_skipped']:.2f}, difference {t['diff']:.2f} (95% day-clustered bootstrap interval "
              f"[{t['lo']:.2f}, {t['hi']:.2f}]); {verdict}.", ""]
    L += ["## Limitations (read before trusting any number)",
          f"- Only {len(folds)} test folds; Sharpe/Sortino over a few months carry wide uncertainty (see the intervals above).",
          "- `model_top_k_permutations` ranks permutations by mean predicted score over the test window, which "
          "uses features of trades later in that window (event *schedule* and as-of-trade-time data only, never "
          "future outcomes), but a live system would have to decide ex ante. Treat it as optimistic relative to "
          "`model_trade_filter`, which is fully causal per trade.",
          "- No transaction costs or slippage beyond what is already in the logged P&L.",
          "- Event surprise z-scores need 3 prior prints, so the first prints of each event carry no signal.",
          "- Hyper-parameters were not tuned; fixed defaults avoid selecting them on the test folds.", ""]
    return "\n".join(L)
